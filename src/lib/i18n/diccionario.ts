const textos: Record<Idioma, Record<Clave, string>> = { es, en };

export function esIdioma(v: unknown): v is Idioma {
  return v === "es" || v === "en";
}

export type Traductor = (clave: Clave, vars?: Record<string, string | number>) => string;

export function crearTraductor(idioma: Idioma): Traductor {
  const tabla = textos[idioma] ?? textos[IDIOMA_BASE];
  return (clave, vars) => {
    let texto = tabla[clave] ?? textos[IDIOMA_BASE][clave] ?? clave;
    if (vars) for (const [k, v] of Object.entries(vars)) texto = texto.replaceAll(`{${k}}`, String(v));
    return texto;
  };
}
